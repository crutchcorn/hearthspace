//! Construct the real geometry owner without session startup or service workers.
use crate::compositor::*;

pub(super) fn new(dh: &DisplayHandle, handle: LoopHandle<'static, CalloopData>) -> App {
    let mut seat_state = SeatState::new();
    let mut seat = seat_state.new_wl_seat(dh, "callback-geometry");
    let keyboard = seat.add_keyboard(Default::default(), 200, 25).unwrap();
    let pointer = seat.add_pointer();
    let touch = seat.add_touch();
    let dmabuf = create_dmabuf_global(dh, Vec::new(), None).unwrap();
    let settings = hearthspace_ipc::Settings::default();
    App {
        display_handle: dh.clone(),
        compositor_state: CompositorState::new::<App>(dh),
        xdg_shell_state: XdgShellState::new::<App>(dh),
        _xdg_decoration_state: XdgDecorationState::new::<App>(dh),
        _output_manager_state: OutputManagerState::new_with_xdg_output::<App>(dh),
        _viewporter_state: ViewporterState::new::<App>(dh),
        _fractional_scale_manager_state: FractionalScaleManagerState::new::<App>(dh),
        #[cfg(feature = "xwayland")]
        _xwayland_shell_state: XWaylandShellState::new::<App>(dh),
        shm_state: ShmState::new::<App>(dh, []),
        seat_state,
        data_device_state: DataDeviceState::new::<App>(dh),
        primary_selection_state: PrimarySelectionState::new::<App>(dh),
        session_lock: session_lock::LockState::new(dh, true),
        remote_input: input::RemoteInput::new(dh, false),
        remote_capture: capture::protocol::RemoteCaptureState::new(dh, false),
        gtk_shell: gtk_shell::GtkShellState::new(dh),
        _seat: seat,
        pointer,
        touch,
        ui_touch: None,
        titlebar_input: Default::default(),
        focused_shell_peek: Default::default(),
        pressed_pointer_buttons: Default::default(),
        keyboard,
        viewport_offset: CanvasPoint { x: 0, y: 0 },
        layout_store: layout::LayoutStore::in_memory(),
        layout_editor: Default::default(),
        power_confirmation: None,
        desktop: Default::default(),
        canvas_peek: canvas_peek::State::with_homes(Default::default()),
        canvas_search: Default::default(),
        canvas_preview: Default::default(),
        viewport_scale: 1.,
        viewport_animation: None,
        window_switcher: Default::default(),
        window_group: Default::default(),
        switcher_input: Default::default(),
        pinch_zoom: Default::default(),
        canvas_pan: Default::default(),
        windows: Default::default(),
        idle_daemon: WindowIdleDaemon::new(WINDOW_IDLE_THRESHOLDS),
        settings_subscription: settings_watch::Subscription::disconnected(),
        titlebar_icons: Default::default(),
        focused_normal_window_id: None,
        shortcuts: Default::default(),
        search_request: Default::default(),
        control_events: Default::default(),
        favorite_drawing: Default::default(),
        drag: None,
        resize: None,
        cursor_icon: CursorIcon::Default,
        cursor_visible: true,
        cursor_surface: None,
        next_spawn_output_name: None,
        snap_wayland_socket_paths: Default::default(),
        pointer_location: (0., 0.).into(),
        raw_pointer_location: (0., 0.).into(),
        touch_input: Default::default(),
        dispatching_touch: false,
        touch_pointer_pressed: false,
        scroll_zooms_without_super: false,
        outputs: OutputSet::for_callback_tests(dh),
        app_catalog: Default::default(),
        needs_redraw: false,
        dmabuf_state: dmabuf.state,
        _dmabuf_global: dmabuf.global,
        #[cfg(feature = "udev")]
        dmabuf_feedback_surfaces: Vec::new(),
        pending_dmabuf_imports: Vec::new(),
        loop_handle: handle,
        popups: PopupManager::default(),
        popup_grab: None,
        background_mode: settings.background_mode,
        appearance: settings.appearance,
        palette: hearthspace_ui_components::Palette::new(settings.appearance),
        background_image_path: None,
        background_image_tile: None,
        corner_blur: Default::default(),
        window_backdrop: Default::default(),
        window_frames: Default::default(),
        background_tile_ids: Vec::new(),
        software_cursor_visible: false,
        software_cursor: cursor::standard_software_cursor(),
        #[cfg(feature = "xwayland")]
        xwm: None,
        #[cfg(feature = "xwayland")]
        xdisplay: None,
    }
}
